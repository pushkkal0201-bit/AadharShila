"""Deterministic synthetic evaluation fixture for *pipeline tests only*.

The labels are generated from an invented statistical relationship. They do not
represent borrowers, actual defaults, lending performance or model validation.
"""
from __future__ import annotations
import argparse
import csv
import json
import math
import random
from datetime import date, timedelta
from pathlib import Path
from .risk_training import train


def generate_synthetic(output_dir: Path, *, rows: int = 640, seed: int = 42) -> tuple[Path,Path]:
    if rows < 300 or rows > 20000:raise ValueError('Choose between 300 and 20,000 synthetic records')
    output_dir=Path(output_dir);output_dir.mkdir(parents=True,exist_ok=True)
    rng=random.Random(seed)
    csv_path=output_dir/'synthetic_mortgage_history.csv'
    manifest_path=output_dir/'synthetic_manifest.json'
    names=['borrower_id','decision_date','foir','ltv','monthly_surplus_ratio',
           'obligation_to_income_ratio','income_volatility','credit_utilization','default_12m']
    with csv_path.open('w',newline='',encoding='utf-8') as dest:
        w=csv.DictWriter(dest,fieldnames=names);w.writeheader()
        for i in range(rows):
            foir=rng.uniform(.08,.78)
            ltv=rng.uniform(.20,.98)
            volatility=rng.uniform(.02,.55)
            utilization=rng.uniform(.02,.97)
            obligations=rng.uniform(.02,.50)
            surplus=max(0,.95-foir-rng.uniform(.02,.25))
            # This is an invented mathematical rule, NOT a real credit risk PD.
            logit=-2.3+2.8*(foir-.35)+1.8*(ltv-.7)+1.2*volatility+1.1*utilization
            invented_probability=1/(1+math.exp(-logit))
            label=int(rng.random()<invented_probability)
            day=date(2021,1,1)+timedelta(days=int(i*2.1))
            w.writerow({'borrower_id':f'SYN-{seed}-{i:06d}','decision_date':day.isoformat(),
                        'foir':round(foir,6),'ltv':round(ltv,6),
                        'monthly_surplus_ratio':round(surplus,6),
                        'obligation_to_income_ratio':round(obligations,6),
                        'income_volatility':round(volatility,6),
                        'credit_utilization':round(utilization,6),'default_12m':label})
    manifest={'source':f'SYNTHETIC_FORMULA_GENERATOR_V1_SEED_{seed}',
              'license':'Generated by this repository; no real people or source data',
              'permission':'Engineering demonstration and automated regression testing only',
              'label_definition':'Invented simulated binary outcome; not observed default',
              'horizon_months':12,
              'features':['foir','ltv','monthly_surplus_ratio','obligation_to_income_ratio',
                          'income_volatility','credit_utilization'],
              'synthetic':True,'decision_date_column':'decision_date',
              'borrower_id_column':'borrower_id'}
    manifest_path.write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    return csv_path,manifest_path


def run(output_dir: Path, *, rows: int = 640, seed: int = 42) -> dict:
    csv_path,manifest=generate_synthetic(output_dir,rows=rows,seed=seed)
    metrics=train(csv_path,manifest,Path(output_dir)/'research_model.json')
    return {'status':'SYNTHETIC_TEST_ONLY','seed':seed,'rows':rows,
            'model_activated':False,'holdout_test':metrics['holdout_test'],
            'limitations':metrics['limitations']}


def main():
    p=argparse.ArgumentParser(description='Generate and evaluate entirely synthetic research records')
    p.add_argument('--output-dir',required=True,type=Path)
    p.add_argument('--seed',type=int,default=42)
    p.add_argument('--rows',type=int,default=640)
    args=p.parse_args()
    print(json.dumps(run(args.output_dir,rows=args.rows,seed=args.seed),indent=2))

if __name__=='__main__':main()
